const secretPrefixes = ['x-amz-', 'x-goog-', 'oauth_', '__cf_chl_', 'cf_chl_'];
const secretFragments = ['token', 'secret', 'password', 'apikey', 'api_key'];
const authPath =
  /(?:^|\/)(?:oauth2?|authorize|callback|signin|sign-in|login|logout|sso|saml|auth|consent)(?:\/|$)/i;

function matchesHost(host: string, pattern: string): boolean {
  if (!pattern.startsWith('*.')) return host === pattern;
  const domain = pattern.slice(2);
  return host === domain || host.endsWith('.' + domain);
}

function isJwt(value: string): boolean {
  if (!/^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/.test(value)) return false;
  try {
    const header: unknown = JSON.parse(Buffer.from(value.split('.')[0], 'base64url').toString('utf8'));
    return typeof header === 'object' && header !== null && !Array.isArray(header) && 'alg' in header;
  } catch {
    return false;
  }
}

/** The URL as it should be remembered: trackers and secrets removed. Returns null when nothing safe remains to remember. */
export function cleanUrl(value: string): string | null {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    return null;
  }
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password) return null;
  url.hash = '';
  const siteParameters = new Set(
    siteTrackingParameters
      .filter((rule) => rule.hosts.some((host) => matchesHost(url.hostname, host)))
      .flatMap((rule) => rule.params),
  );
  const parameters = new URLSearchParams();
  for (const [name, value] of url.searchParams) {
    const key = name.toLowerCase();
    if (key.startsWith('utm_') || trackingParameters.has(key) || siteParameters.has(key)) continue;
    if (
      secretParameters.has(key) ||
      secretPrefixes.some((prefix) => key.startsWith(prefix)) ||
      secretFragments.some((fragment) => key.includes(fragment)) ||
      isJwt(value)
    )
      continue;
    parameters.append(name, value);
  }
  parameters.sort();
  url.search = authPath.test(url.pathname) ? '' : parameters.toString();
  return url.href;
}
