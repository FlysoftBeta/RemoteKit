import test from 'node:test';
import assert from 'node:assert/strict';
import { PresentationDiagnostics } from '../client/presentation-diagnostics';
test('presentation counters distinguish late metadata, overwritten frames and duplicate observations', () => {
  const metrics = new PresentationDiagnostics();
  metrics.video(10, 100, '1', undefined, { presentedFrames: 1, decoded: 1 });
  metrics.frameMetadata(15, 100, '1');
  metrics.authorize(16, 100, '1');
  metrics.video(17, 100, '1', '1', { presentedFrames: 1, decoded: 1 });
  assert.equal(metrics.snapshot().epoch.pending, null);
  metrics.video(20, 101, '1', undefined, { presentedFrames: 2, decoded: 2 });
  metrics.video(30, 102, '1', undefined, { presentedFrames: 3, decoded: 3 });
  metrics.frameMetadata(35, 101, '1');
  const report = metrics.snapshot(true);
  assert.equal(report.rawRvfcCount, 4);
  assert.equal(report.epoch.matched, 1);
  assert.equal(report.epoch.missed, 1);
  assert.equal(report.epoch.lateMetadataForMissed, 1);
  assert.equal(report.epoch.pending?.rtp, 102);
  assert.equal(report.authorizeWaitMs.p50, 6);
  assert.equal(report.metadataRelativeToVideoMs.p50, 5);
});
